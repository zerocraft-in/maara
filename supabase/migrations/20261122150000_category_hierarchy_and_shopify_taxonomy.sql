create or replace function private.set_category_parent(
  p_category_id uuid,
  p_parent_id uuid
) returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_organization_id uuid;
  v_old_parent_id uuid;
  v_cursor uuid;
  v_parent_organization_id uuid;
begin
  select c.organization_id, c.parent_id
  into v_organization_id, v_old_parent_id
  from public.categories c
  where c.id = p_category_id
  for update of c;

  if not found then
    raise exception 'Category not found';
  end if;

  if not private.is_member(v_organization_id)
     or not private.has_permission(v_organization_id, 'categories.manage') then
    raise exception 'Caller does not have category management permission in this organization';
  end if;

  if p_parent_id is not null then
    if p_parent_id = p_category_id then
      raise exception 'A category cannot be its own parent';
    end if;

    select c.organization_id
    into v_parent_organization_id
    from public.categories c
    where c.id = p_parent_id;

    if not found or v_parent_organization_id <> v_organization_id then
      raise exception 'Parent category must belong to the same organization';
    end if;

    v_cursor := p_parent_id;
    while v_cursor is not null loop
      if v_cursor = p_category_id then
        raise exception 'Category hierarchy cannot contain a cycle';
      end if;
      select c.parent_id into v_cursor
      from public.categories c
      where c.id = v_cursor
        and c.organization_id = v_organization_id;
    end loop;
  end if;

  if v_old_parent_id is distinct from p_parent_id then
    update public.categories
    set parent_id = p_parent_id,
        updated_at = now()
    where id = p_category_id;

    insert into public.audit_logs
      (organization_id, actor_user_id, action, entity_type, entity_id, metadata, created_at)
    values
      (v_organization_id, auth.uid(), 'category.parent_changed', 'category', p_category_id,
       jsonb_build_object('old_parent_id', v_old_parent_id, 'new_parent_id', p_parent_id), now());
  end if;
end;
$$;

revoke all on function private.set_category_parent(uuid, uuid) from public, anon, authenticated;

